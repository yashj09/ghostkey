// Generates src/generated.ts (ABI + creation bytecode) from the Foundry build in contracts/out.
// Run `forge build` in contracts/ first, then: pnpm -F @ghostkey/core gen
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");
const targets: [exportName: string, file: string, contract: string][] = [
  ["PQDelegate", "PQDelegate.sol", "PQDelegate"],
  ["PQAccount", "PQAccount.sol", "PQAccount"],
  ["QuantumCanary", "QuantumCanary.sol", "QuantumCanary"],
  ["LeanSphincsSAsm", "LeanSphincs-SAsm.sol", "LeanSphincsSAsm"],
];

let src = "// AUTO-GENERATED by scripts/gen-artifacts.ts from contracts/out. Do not edit.\n\n";
for (const [name, file, contract] of targets) {
  const art = JSON.parse(readFileSync(resolve(out, file, `${contract}.json`), "utf8"));
  src += `export const ${name} = {\n  abi: ${JSON.stringify(art.abi)} as const,\n  bytecode: "${art.bytecode.object}" as \`0x\${string}\`,\n} as const;\n\n`;
}
writeFileSync(resolve(here, "../src/generated.ts"), src);
console.log(`wrote ${targets.length} artifacts`);
